"""Extract the Sanskrit text of the Bhagavad Gita from a source JSON into gita_tft/data/gita_sanskrit.json, and check it.

    python -m gita_tft.prepare_text --source verse.json            (verse.json: https://github.com/gita/gita, data/verse.json, Unlicense)

Only the Sanskrit is taken (the original is ancient; this edition's text is in the public domain via that repository's Unlicense).
Translations, word meanings and transliteration in the source are NOT used: transliteration is generated by code (see text.py).
Nothing is written, rewritten or invented here: a verse is its source text split into speaker line, verse lines and reference.
"""
import argparse
import json
import re
from pathlib import Path

VERSES_PER_CHAPTER = [47, 72, 43, 42, 29, 47, 30, 28, 34, 42, 55, 20, 35, 27, 20, 24, 28, 78]      # 701 in this edition
MARK = re.compile(r"।।\s*(\d+)\.(\d+)\s*।{1,2}")      # the source closes 18.78 with a single danda
DEVANAGARI = re.compile(r"^[ऀ-ॿ‌‍ ]+$")

def parse_verse(raw):
    body = raw.strip()
    m = MARK.search(body)
    if not m:
        raise ValueError("verse has no ।।c.v।। marker")
    chapter, verse = int(m.group(1)), int(m.group(2))
    body = (body[:m.start()] + body[m.end():]).strip()
    parts = [p.strip() for p in re.split(r"\n\s*\n|\n", body) if p.strip()]
    speaker = ""
    # A speaker line is short, has no danda and ends in -vāca ("अर्जुन उवाच", and the joined form "श्री भगवानुवाच").
    if len(parts) >= 2 and "।" not in parts[0] and len(parts[0]) < 25 and parts[0].rstrip().endswith("वाच"):
        speaker = parts.pop(0)
    lines = parts
    if not lines:
        raise ValueError("verse has no text")
    return {"chapter": chapter, "verse": verse, "speaker": speaker, "lines": lines}

def validate(chapters):
    problems = []
    if [len(c) for c in chapters] != VERSES_PER_CHAPTER:
        problems.append(f"verse counts {[len(c) for c in chapters]} != {VERSES_PER_CHAPTER}")
    for ci, c in enumerate(chapters, 1):
        for vi, v in enumerate(c, 1):
            if (v["chapter"], v["verse"]) != (ci, vi):
                problems.append(f"marker {v['chapter']}.{v['verse']} at position {ci}.{vi}")
            for line in ([v["speaker"]] if v["speaker"] else []) + v["lines"]:
                if not DEVANAGARI.match(line.replace("।", "").replace("ऽ", "ऽ")):
                    problems.append(f"{ci}.{vi}: unexpected characters in {line[:30]!r}")
    return problems

def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--source", required=True)
    p.add_argument("--out", default=str(Path(__file__).parent / "data" / "gita_sanskrit.json"))
    args = p.parse_args(argv)
    raw = json.loads(Path(args.source).read_text(encoding="utf-8"))
    raw.sort(key=lambda r: (int(r["chapter_number"]), int(r["verse_number"])))
    chapters = [[] for _ in range(18)]
    for r in raw:
        v = parse_verse(r["text"])
        if v["chapter"] != int(r["chapter_number"]) or v["verse"] != int(r["verse_number"]):
            raise SystemExit(f"marker {v['chapter']}.{v['verse']} disagrees with the record {r['chapter_number']}.{r['verse_number']}")
        chapters[v["chapter"] - 1].append(v)
    problems = validate(chapters)
    if problems:
        raise SystemExit("INVALID SOURCE:\n" + "\n".join(problems[:20]))
    Path(args.out).write_text(json.dumps({"chapters": chapters}, ensure_ascii=False, indent=0), encoding="utf-8")
    print("wrote", args.out, sum(len(c) for c in chapters), "verses")

if __name__ == "__main__":
    main()
